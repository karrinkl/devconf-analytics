/*
  Демонстрационные вопросы. Нужны, чтобы страница аналитики
  не открывалась пустой, пока форму ещё никто не заполнял.
  Если в базе уже есть вопросы, скрипт запуска их не трогает.
*/

const sampleQuestions = [
  ['Алексей Ковалёв', 5],
  ['Дарья Мельник', 3],
  ['Игорь Савчук', 4],
  ['Марина Ярош', 2],
  ['Павел Бортник', 6],
  ['Ольга Лагун', 1],
  ['Антон Демчук', 4],
  ['Вероника Руденко', 2],
];

const phrases = [
  'Можно короткий пример из практики?',
  'Какие инструменты вы используете сами?',
  'С чего начать, если команда небольшая?',
  'Что обычно ломается первым?',
  'Будут ли материалы после доклада?',
  'Как это проверить на своём проекте?',
];

const questions = sampleQuestions.flatMap(([speakerName, count]) =>
  Array.from({ length: count }, (_, index) => ({
    author: 'Зритель',
    speakerName,
    text: phrases[index % phrases.length],
  }))
);

module.exports = questions;
